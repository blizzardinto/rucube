#include "Cube.h"
#include <cstdlib>

// ============================================================================
// 🧱 7 种标准俄罗斯方块 (Tetromino) 局部偏移表
// 
// 【坐标系约定】
// 控制台坐标系中，X 轴向右为正，Y 轴向下为正。
// 每个方块由 4 个小格子组成，每个格子用相对于锚点 (mX, mY) 的偏移 {dx, dy} 表示：
//
// 1. I 型（长条）:    [ ][ ][ ][ ]   (横向 4 格)
// 2. O 型（田字）:    [ ][ ]
//                    [ ][ ]
// 3. T 型（凸字）:       [ ]
//                    [ ][ ][ ]
// 4. S 型（反Z）:        [ ][ ]
//                    [ ][ ]
// 5. Z 型（正Z）:    [ ][ ]
//                        [ ][ ]
// 6. J 型（反L）:    [ ]
//                    [ ][ ][ ]
// 7. L 型（正L）:          [ ]
//                    [ ][ ][ ]
// ============================================================================
const int Cube::SHAPES[Cube::Type::COUNT][4][2] = {
    // I 型
    { {0,1}, {1,1}, {2,1}, {3,1} },
    // O 型
    { {0,0}, {1,0}, {0,1}, {1,1} },
    // T 型
    { {0,1}, {1,1}, {2,1}, {1,0} },
    // S 型
    { {1,0}, {2,0}, {0,1}, {1,1} },
    // Z 型
    { {0,0}, {1,0}, {1,1}, {2,1} },
    // J 型
    { {0,0}, {0,1}, {1,1}, {2,1} },
    // L 型
    { {2,0}, {0,1}, {1,1}, {2,1} },
};

// ============================================================================
// 每种方块的专属配色表
// ============================================================================
const Color Cube::COLORS[Cube::Type::COUNT] = {
    Color::BrightCyan,     // I: 青色
    Color::BrightYellow,   // O: 黄色
    Color::BrightMagenta,  // T: 品红/紫色
    Color::BrightGreen,    // S: 绿色
    Color::BrightRed,      // Z: 红色
    Color::BrightBlue,     // J: 蓝色
    Color::White,          // L: 白色
};

// ============================================================================
// 构造函数：初始化方块
// 
// 【C++ 知识点：构造函数初始化列表 (Initializer List)】
// : mType(t), mX(SPAWN_X), mY(SPAWN_Y)
// 这是 C++ 推荐的做法！它在对象内存刚分配出来时直接进行“初始化”，
// 效率比在花括号 {} 里面写赋值语句（先默认构造再赋值）更高！
// ============================================================================
Cube::Cube(Type t)
    : mType(t), mX(SPAWN_X), mY(SPAWN_Y) {
    // 从静态表拷贝该形状的 4 个格子相对偏移
    for (int i = 0; i < 4; i++) {
        mOff[i][0] = SHAPES[t][i][0];
        mOff[i][1] = SHAPES[t][i][1];
        mOld[i][0] = mOff[i][0];
        mOld[i][1] = mOff[i][1];
    }
}

// ============================================================================
// 移动行为：改变锚点坐标
// ============================================================================
void Cube::move(int dx, int dy) {
    mX += dx;
    mY += dy;
}

// ============================================================================
// 旋转行为：顺时针旋转 90 度
//
// 【📐 数学小讲堂：二维平面顺时针旋转 90°】
// 在普通数学笛卡尔坐标系中（Y 向上），顺时针旋转 90° 的变换公式是 (x, y) -> (y, -x)。
// 但在计算机屏幕坐标系中，Y 轴是朝下的！
// 经过推导，屏幕坐标系下的顺时针 90° 旋转对应：
//   new_x =  old_y
//   new_y = -old_x
// 旋转后，部分格子的坐标可能会变成负数。
// 因此我们做一次“归一化/重对齐”：减去最小的 minX 和 minY，
// 这样方块就始终紧贴包围盒的左上角 (0, 0)，非常稳定可靠！
// ============================================================================
void Cube::rotate() {
    // 1. 备份当前状态（供撞墙时 restore 回滚）
    for (int i = 0; i < 4; i++) {
        mOld[i][0] = mOff[i][0];
        mOld[i][1] = mOff[i][1];
    }

    // 2. 顺时针旋转并找最小值
    int nx[4], ny[4];
    int minX = 0, minY = 0;
    for (int i = 0; i < 4; i++) {
        nx[i] =  mOff[i][1];
        ny[i] = -mOff[i][0];
        if (nx[i] < minX) minX = nx[i];
        if (ny[i] < minY) minY = ny[i];
    }

    // 3. 归一化对齐：把偏移移回 >= 0 的区间
    for (int i = 0; i < 4; i++) {
        mOff[i][0] = nx[i] - minX;
        mOff[i][1] = ny[i] - minY;
    }
}

// ============================================================================
// 回滚行为：撤销上次旋转（撞墙/卡住时的悔棋操作）
// ============================================================================
void Cube::restore() {
    for (int i = 0; i < 4; i++) {
        mOff[i][0] = mOld[i][0];
        mOff[i][1] = mOld[i][1];
    }
}

// ============================================================================
// 现代 C++ 接口：返回 4 个格子的绝对坐标数组 (std::array)
// 绝对坐标 = 锚点坐标 (mX, mY) + 格子相对偏移 (mOff[i][0], mOff[i][1])
// ============================================================================
std::array<Cube::Cell, 4> Cube::cells() const {
    std::array<Cell, 4> result;
    for (int i = 0; i < 4; i++) {
        result[i].x = mX + mOff[i][0];
        result[i].y = mY + mOff[i][1];
    }
    return result;
}

// 传统接口实现：填充传出参数
void Cube::cells(Cell out[4]) const {
    for (int i = 0; i < 4; i++) {
        out[i].x = mX + mOff[i][0];
        out[i].y = mY + mOff[i][1];
    }
}

// ============================================================================
// 获取当前方块颜色
// ============================================================================
Color Cube::color() const {
    return COLORS[mType];
}

// ============================================================================
// 静态工厂方法：随机生成一种方块类型
// ============================================================================
Cube::Type Cube::randomType() {
    return static_cast<Type>(rand() % Type::COUNT);
}

// ============================================================================
// 计算方块的相对包围盒（Bound Box）
// 用于 Next 预览框内让方块水平和垂直居中显示
// ============================================================================
void Cube::bounds(int& minX, int& minY, int& maxX, int& maxY) const {
    minX = minY = 9999;
    maxX = maxY = -9999;
    for (int i = 0; i < 4; i++) {
        if (mOff[i][0] < minX) minX = mOff[i][0];
        if (mOff[i][0] > maxX) maxX = mOff[i][0];
        if (mOff[i][1] < minY) minY = mOff[i][1];
        if (mOff[i][1] > maxY) maxY = mOff[i][1];
    }
}

// ============================================================================
// 绘制一个格子（控制台用 2 个半角字符拼成一个正方形，如 "[]"）
// ============================================================================
void Cube::paintCell(Console& con, int x, int y, Color c, char left, char right) {
    con.put(x,     y, left,  c);
    con.put(x + 1, y, right, c);
}

// ============================================================================
// 在棋盘上自绘制当前方块
// 
// 【C++ 知识点：范围 for 循环 (Range-based for loop)】
// for (const auto& cell : cells())
// 简洁优雅！不需要写下标索引 i，编译器自动遍历 array 中的每一个元素。
// const auto& 表示“只读引用”，既安全又免除了多余的内存拷贝。
// ============================================================================
void Cube::draw(Console& con, int px, int py) const {
    for (const auto& cell : cells()) {
        if (cell.y >= 0) {   // 方块刚出生在顶部以上（y < 0）的部分不画
            paintCell(con,
                      px + BORDER + cell.x * CELL_W,
                      py + BORDER + cell.y,
                      color(), '[', ']');
        }
    }
}

// ============================================================================
// 在右侧 Next 预览框内居中绘制
// ============================================================================
void Cube::drawPreview(Console& con, int innerX, int innerY,
                       int innerW, int innerH) const {
    int minX, minY, maxX, maxY;
    bounds(minX, minY, maxX, maxY);

    int pw = (maxX - minX + 1) * CELL_W;   // 方块在屏幕上的字符宽度
    int ph = (maxY - minY + 1);            // 方块在屏幕上的字符高度
    int ox = innerX + (innerW - pw) / 2;   // 水平居中起始坐标
    int oy = innerY + (innerH - ph) / 2;   // 垂直居中起始坐标

    for (int i = 0; i < 4; i++) {
        int sx = ox + (mOff[i][0] - minX) * CELL_W;
        int sy = oy + (mOff[i][1] - minY);
        paintCell(con, sx, sy, color(), '[', ']');
    }
}

