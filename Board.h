#ifndef BOARD_HPP
#define BOARD_HPP

#include "Console.h"
#include "Cube.h"
#include "GameConfig.h"

// ============================================================================
// 🏟️ 棋盘类 (Board) — 面向对象核心思想教学：
//
// 【1. 现实世界比喻：舞台物理环境 + 铁面无私的裁判】
// 如果说 Cube 是舞台上活蹦乱跳的演员，那么 Board 就是承载演员的整个大舞台！
// 它内部维护了一个 10 列 × 20 行的二维网格数组（mGrid）。
//
// 【2. 为什么碰撞检测由 Board 负责？(信息专家原则 Information Expert)】
// 初学者常问：“为什么不是 Cube.checkCollision(Board) 呢？”
// 答：面向对象设计中有一个原则叫【信息专家】——谁拥有做某事所必须的完整数据，谁就负责这个行为！
// 棋盘才知道所有的边界（左墙、右墙、地板）以及过去已经堆积了哪些老方块。
// 所以，裁判权必须完全属于 Board::canPlace()。
//
// 【3. C++ 传参必学技巧：const Cube& c (常量引用传递)】
// - 如果写 Cube c：每次调用函数都会完整拷贝一份方块对象，耗费内存和时间。
// - 如果写 Cube& c：传递的是原对象的“别名/引用”，零拷贝极快，但容易不小心改坏原对象。
// - 写 const Cube& c：既享受了“零拷贝”的高性能，又有了 const“只读”的安全保障！
// ============================================================================
class Board {
public:
    // ------------------------------------------------------------------------
    // 棋盘标准规格：宽 10 格，高 20 格
    // C++ 知识点：static 常量属于类本身，全工程所有地方都可以用 Board::W 访问
    // ------------------------------------------------------------------------
    static const int W     = 10;   // 棋盘宽度（10 列）
    static const int H     = 20;   // 棋盘高度（20 行）
    static const int EMPTY = -1;   // 空格标记（非空时存储方块的 Type 索引以表示颜色）

    // 构造函数：初始化时直接调用 reset() 清空棋盘
    Board() { reset(); }

    // ------------------------------------------------------------------------
    // 状态管理
    // ------------------------------------------------------------------------
    void reset();                                  // 清空整个棋盘网格（新开一局时使用）

    // ------------------------------------------------------------------------
    // 核心游戏规则与物理判定（裁判职责）
    // ------------------------------------------------------------------------
    // 判定方块 c 当前所在位置是否合法（无出界、不与已有砖块重叠）
    bool canPlace(const Cube& c) const;

    // 锁定方块：当下落方块触底后，将其 4 个小格子固化熔铸到 mGrid 中
    void lock(const Cube& c);

    // 扫描并消除所有已被完全填满的行，上方方块自动下落；返回本次消除的行数 (0~4)
    int clearLines();

    // ------------------------------------------------------------------------
    // 渲染绘制
    // ------------------------------------------------------------------------
    // 绘制棋盘边框与网格内所有已固化的方块：(px, py) 为边框左上角屏幕坐标
    void draw(Console& con, int px, int py) const;

    // 绘制当前活动方块 c 的“落点虚影 (Ghost Piece)”
    // 【教学亮点】：实时投影方块落地位置，帮助玩家快速精准落子！
    void drawGhost(Console& con, const Cube& c, int px, int py) const;

    // ------------------------------------------------------------------------
    // 只读查询接口
    // ------------------------------------------------------------------------
    bool occupied(int x, int y) const;             // 查询指定 (x, y) 格子是否已被占据

private:
    // ========================================================================
    // 私有数据：底板的 10x20 二维网格
    // 坐标习惯：mGrid[y][x]，先行后列（y 代表第几行，x 代表第几列）
    // 存储值：Board::EMPTY(-1) 表示空格，>=0 则表示对应方块类型的颜色索引
    // ========================================================================
    int mGrid[H][W];

    // 将网格中存储的整型数值转换为绘制颜色
    static Color cellColor(int v);

    // 内部绘图工具：在棋盘相对坐标 (bx, by) 处画出已固化的 1 格彩色方块
    void drawCell(Console& con, int px, int py, int bx, int by, Color fg) const;

    // 虚拟投影计算：把传入的方块 c 在内存中模拟一路下落到底，返回该副本
    Cube ghost(const Cube& c) const;
};

#endif // BOARD_HPP

