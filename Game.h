#ifndef GAME_HPP
#define GAME_HPP

#include "Console.h"
#include "Cube.h"
#include "Board.h"
#include "Hud.h"
#include "GameConfig.h"

// ============================================================================
// 🎬 游戏总控制器 (Game) — 面向对象核心思想教学：
//
// 【1. 现实世界比喻：整个剧组的总导演兼中介者 (Mediator)】
// 前面我们有了特技演员 (Cube)、舞台与裁判 (Board)、计分板 (Hud)、放映机 (Console)。
// 谁把它们组合在一起，让整个游戏有条不紊地跑起来？
// 就是 Game！
//
// 【2. 面向对象核心原则：组合优于继承 (Favor Composition over Inheritance)】
// Game 类内部包含了：
//   - Console mCon;    (HAS-A: Game 拥有一个控制台)
//   - Board   mBoard;  (HAS-A: Game 拥有一个棋盘)
//   - Cube    mCurrent;(HAS-A: Game 拥有一个当前活动方块)
//   - Cube    mNext;   (HAS-A: Game 拥有一个等待入场的下一个方块)
//   - Hud     mHud;    (HAS-A: Game 拥有一个UI面板)
// 这就是面向对象中最强大的【组合 (Composition)】思想！
// 各个子对象互不干扰，由 Game 统一指挥调度，结构极为清晰。
//
// 【3. 游戏工业界基石：游戏主循环架构 (The Classic Game Loop)】
// 商业游戏（如王者荣耀、原神、塞尔达传说）在底层都是由类似的主循环驱动的：
//
//   ┌────────────────────────────────────────────────────────┐
//   │                while (mRunning) {                      │
//   │    1. processInput();  // 听指令：玩家按了什么键？     │
//   │    2. update();        // 走物理：重力到了吗？下落一格 │
//   │    3. render();        // 刷画面：把所有东西画到双缓冲 │
//   │    4. sleep(20ms);     // 控帧率：每秒跑 50 帧 (50 FPS)│
//   │ }                                                      │
//   └────────────────────────────────────────────────────────┘
// ============================================================================
class Game {
public:
    // 帧率控制：主循环每 20 毫秒跑一轮（相当于 1 秒 50 帧），保证按键极速响应
    static constexpr int FRAME_MS = 20;

    Game();   // 构造函数：初始化各个子系统
    ~Game();  // 析构函数：释放资源，停止背景音乐 (RAII 资源管理思想)

    // 外部唯一公开入口：运行整个游戏生命周期（启动 -> 循环游玩 -> 死亡询问 -> 退出）
    void run();

private:
    // ------------------------------------------------------------------------
    // 内部生命周期与经典 Game Loop 阶段划分
    // ------------------------------------------------------------------------
    void init();                            // 引擎启动：初始化控制台窗口与随机数种子
    void reset();                           // 单局重置：清空棋盘、重置分数、生成首批方块
    void gameLoop();                        // 单局主循环（Input -> Update -> Render）
    void processInput();                    // 第 1 步：读取并响应玩家按键事件
    void update();                          // 第 2 步：物理推进（重力时钟计时、自动下落）
    void render();                          // 第 3 步：渲染呈现画面
    void renderPaused();                    // 特殊渲染：绘制暂停遮罩画面
    bool showGameOver();                    // 游戏结束：死亡红字闪烁动效，询问是否再来一局 (Y/N)

    // ------------------------------------------------------------------------
    // 规则与公式计算
    // ------------------------------------------------------------------------
    // 触底锁定方块、消除计分并切换下一块；返回 true 表示出生点被堵死（Game Over!）
    bool lockAndAdvance();                  
    // 难度速度公式：根据等级计算方块下落间隔毫秒（速度平滑线性增加）
    static int dropIntervalFor(int level);  
    // 阶梯计分公式：消 1/2/3/4 行的基础分乘以当前等级倍率
    static int lineScore(int lines, int level); 

private:
    // ========================================================================
    // 组合的各个子模块（演员与舞台）
    // ========================================================================
    Console mCon;      // 控制台平台抽象层（双缓冲、屏幕、键盘输入）
    Hud     mHud;      // 界面信息与提示板
    Board   mBoard;    // 棋盘网格、物理碰撞与满行消除裁判
    Cube    mCurrent;  // 当前正在空中下落的活动方块
    Cube    mNext;     // 下一个即将登场的方块

    // ========================================================================
    // 游戏核心状态数据 (State)
    // C++ 知识点：C++11 允许在成员声明时直接给初始值 (In-class member initializers)
    // ========================================================================
    int     mScore        = 0;          // 当前总得分
    int     mLines        = 0;          // 累计已消除的总行数
    int     mLevel        = 1;          // 当前游戏等级（每消 10 行升一级）
    int     mDropTimer    = 0;          // 重力下落累积计时器（毫秒）
    int     mDropInterval = 500;        // 当前等级对应的下落时间间隔（毫秒）

    bool    mRunning      = false;      // 单局游戏是否正在进行中
    bool    mPaused       = false;      // 游戏是否处于暂停状态
    bool    mQuit         = false;      // 玩家是否决定彻底退出程序
};

#endif // GAME_HPP

