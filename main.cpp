#include "Game.h"

// ============================================================================
// 🚀 程序总入口 (main.cpp) — 面向对象程序设计的优雅之美：
//
// 【给初学 C++ 的你：为什么 main 函数只有短短两行代码？】
//
// 很多初学 C 语言或 C++ 的同学，习惯把成百上千行的逻辑、各种全局变量全都堆在 main() 里，
// 这叫“面向过程（Procedural Programming）”的线性思维，代码越写越像一团乱麻（意大利面条代码）。
//
// 而在【面向对象编程 (Object-Oriented Programming, OOP)】的世界里：
// 1. 我们把游戏抽象成了一个个独立的实体（Game、Board、Cube、Hud、Console）；
// 2. main 函数不再亲自去做任何具体的细节工作；
// 3. main 函数唯一的职责就是：【实例化游戏对象 (Game game)】并【启动引擎 (game.run())】！
//
// 一切具体的初始化、主循环、物理更新、碰撞判断、音效与画面渲染，
// 全部被整齐地封装在对应的类里面。这就是软件工程中推崇的“高内聚、低耦合、职责分明”！
// ============================================================================
int main(int argc, char* argv[]) {
    Game game;     // 1. 创建游戏控制器实例（自动调用 Game 的构造函数）
    game.run();    // 2. 启动游戏主循环与完整生命周期
    return 0;      // 3. 正常退出（自动调用 Game 的析构函数释放资源）
}

