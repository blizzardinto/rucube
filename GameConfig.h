#ifndef GAMECONFIG_HPP
#define GAMECONFIG_HPP

// ============================================================================
// 🎮 游戏全局配置 (GameConfig.h) — 给初学者的话：
// 
// 【面向对象思考：为什么需要这个文件？】
// 在写代码时，如果各个类到处写着 80, 30, 2 这样的数字，就叫“魔法数字”（Magic Numbers）。
// 一旦某天你想改游戏屏幕大小，就得满世界找每个文件去改，极容易漏掉或改错。
// 把所有【全局规则与布局常量】集中到这里，就像是给整个工程制定了一份“统一尺寸图纸”。
//
// 【C++ 知识点：constexpr 是什么？】
// - constexpr 是 C++11/14 引入的现代关键字，表示“编译期常量”。
// - 它比传统的 C 语言宏（#define SCREEN_W 80）好很多：它具有明确的数据类型（int），
//   并且遵循作用域规则，不容易引发隐蔽的宏替换 BUG。
// ============================================================================

// ----------------------------------------------------------------------------
// 1. 控制台虚拟屏幕尺寸（字符单位）
// ----------------------------------------------------------------------------
constexpr int SCREEN_W = 80;  // 屏幕宽度：80 个字符
constexpr int SCREEN_H = 30;  // 屏幕高度：30 个字符

// ----------------------------------------------------------------------------
// 2. 棋盘格子渲染比例
// 【为什么宽度是 2？】
// 计算机控制台终端里的英文字符通常是“长方形”的（高是宽的约 2 倍）。
// 为了让俄罗斯方块在屏幕上看起来是“正方形”，每个游戏格子横向需要占 2 个字符宽度！
// ----------------------------------------------------------------------------
constexpr int CELL_W = 2;    // 每个游戏格子在屏幕上占用的字符宽度（宽2、高1 -> 视觉呈正方形）
constexpr int BORDER = 1;    // 绘制外边框时的单边厚度（1 个字符）

// ----------------------------------------------------------------------------
// 3. 棋盘在控制台屏幕上的起始位置（锚点坐标）
// 控制台坐标系特点：左上角是 (0, 0)，X 轴向右递增，Y 轴向下递增。
// ----------------------------------------------------------------------------
constexpr int BOARD_PX = 30;  // 棋盘边框左上角的 X 坐标（横向居中偏左）
constexpr int BOARD_PY = 4;   // 棋盘边框左上角的 Y 坐标（距离顶部留出 4 行空间）

// ----------------------------------------------------------------------------
// 4. "NEXT" 下一个方块预览框的位置与尺寸
// ----------------------------------------------------------------------------
constexpr int NEXT_X = 58;    // 预览框左上角 X（放在主棋盘右侧）
constexpr int NEXT_Y = 4;     // 预览框左上角 Y
constexpr int NEXT_W = 12;    // 预览框宽度（字符）
constexpr int NEXT_H = 7;     // 预览框高度（字符）

#endif // GAMECONFIG_HPP

