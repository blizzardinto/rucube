#ifndef SOUND_HPP
#define SOUND_HPP

// ============================================================================
// 🔊 音频子系统 (Sound) — 多线程与并发编程核心思想教学：
//
// 【1. 为什么音效必须放在“独立线程”中播放？】
// 很多初学 C++ 的同学用 Windows 的 Beep(frequency, duration) 播放声音，
// 会发现一个诡异现象：每次一响，游戏画面就卡住不动，声音停了画面才动！
// 为什么？
// 因为 Beep 函数是“同步阻塞 (Synchronous Blocking)”的！如果响 300 毫秒，
// 整个主线程就会死等 300 毫秒，游戏主循环直接停滞！
//
// 本项目解决方案：
// 采用【多线程异步并发 (Asynchronous Multithreading)】设计！
// 当发生旋转或消行时，主线程只负责“发一条通知（playSfx）”，然后毫不停留继续推进游戏；
// 后台有一个默默无闻的工作线程负责真正去发声，两者互不干扰，游戏极其流畅！
//
// 【2. 程序化合成背景音乐 (Procedural Chiptune Audio)】
// 整个游戏完全不需要任何外部的 .mp3 或 .wav 文件！
// Sound.cpp 内部利用正弦波/方波数学公式，在内存中动态生成 8-bit 复古电子音乐并循环混音，
// 是学习计算机音频原理的绝佳范例。
// ============================================================================

// ----------------------------------------------------------------------------
// 游戏音效枚举
// ----------------------------------------------------------------------------
enum class Sfx {
    Start,      // 游戏开场：轻快上行三连音
    Rotate,     // 方块旋转：短促灵动的“滴”声
    Drop,       // 方块落地：低沉结实的“咚”声
    Clear1,     // 消除 1 行：单音消除提示
    Clear2,     // 消除 2 行：双音连奏
    Clear3,     // 消除 3 行：三音爬升
    Clear4,     // 消除 4 行（Tetris！）：华丽上行琶音 + 兴奋的高音爆发！
    SpeedUp,    // 速度等级提升：急促警示音
    GameOver,   // 游戏结束：经典下行哀伤旋律 + 低音沉落
};

// ----------------------------------------------------------------------------
// 音效播放接口（异步非阻塞，主线程调用后立即返回）
// force = true 表示强制排队播放，绝不被丢弃（用于 GameOver 等重要结算音效）
// ----------------------------------------------------------------------------
void playSfx(Sfx s, bool force = false);

// 音效全局开关控制
void setSoundEnabled(bool on);
bool soundEnabled();

// ----------------------------------------------------------------------------
// 背景音乐 (BGM) 控制接口
// ----------------------------------------------------------------------------
void startMusic();  // 开始在内存中合成并循环播放复古 Chiptune BGM
void stopMusic();   // 停止背景音乐

#endif // SOUND_HPP

